import React, { useCallback, useEffect, useRef, useState } from "react";
import {
  Bar,
  BarChart,
  CartesianGrid,
  ResponsiveContainer,
  Tooltip,
  XAxis,
  YAxis,
} from "recharts";
import { api } from "./api.js";

const LEVELS = ["", "FATAL", "ERROR", "WARN", "INFO", "UNKNOWN"];

function TrendBadge({ trend }) {
  return <span className={`badge trend-${trend}`}>{trend}</span>;
}

function LevelBadge({ level }) {
  return <span className={`badge level-${level}`}>{level}</span>;
}

function ClusterDetail({ id, onClose }) {
  const [detail, setDetail] = useState(null);
  const [points, setPoints] = useState([]);
  const [summary, setSummary] = useState(null);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState("");

  useEffect(() => {
    let cancelled = false;
    setDetail(null);
    setSummary(null);
    setError("");
    Promise.all([api.detail(id), api.trend(id)])
      .then(([d, t]) => {
        if (cancelled) return;
        setDetail(d);
        setSummary(d.summary ? { text: d.summary, used_llm: true } : null);
        setPoints(
          t.points.map((p) => ({
            hour: new Date(p.hour + "Z").toLocaleString([], {
              month: "short",
              day: "numeric",
              hour: "2-digit",
            }),
            count: p.count,
          }))
        );
      })
      .catch((e) => !cancelled && setError(e.message));
    return () => {
      cancelled = true;
    };
  }, [id]);

  async function summarize() {
    setBusy(true);
    setError("");
    try {
      const r = await api.summarize(id, true);
      setSummary({
        text: r.summary,
        used_llm: r.used_llm,
        provider: r.provider,
        reason: r.reason,
      });
    } catch (e) {
      setError(e.message);
    } finally {
      setBusy(false);
    }
  }

  return (
    <aside className="detail">
      <button className="close" onClick={onClose} aria-label="Close details">
        ×
      </button>
      {error && <p className="error">{error}</p>}
      {!detail && !error && <p className="muted">Loading…</p>}
      {detail && (
        <>
          <h2>
            <LevelBadge level={detail.level} /> <TrendBadge trend={detail.trend} />
          </h2>
          <p className="template">{detail.template}</p>
          <p className="muted">
            {detail.total_count.toLocaleString()} occurrences · last hour in data:{" "}
            {detail.recent_count} (previous hour: {detail.previous_count})
          </p>

          <h3>Occurrences per hour</h3>
          <div className="chart">
            <ResponsiveContainer width="100%" height={180}>
              <BarChart data={points}>
                <CartesianGrid strokeDasharray="3 3" vertical={false} />
                <XAxis dataKey="hour" tick={{ fontSize: 11 }} interval="preserveStartEnd" />
                <YAxis allowDecimals={false} tick={{ fontSize: 11 }} width={40} />
                <Tooltip />
                <Bar dataKey="count" fill="#3b6fd4" />
              </BarChart>
            </ResponsiveContainer>
          </div>

          <h3>Summary</h3>
          {summary ? (
            <>
              <p className="summary">{summary.text}</p>
              {summary.used_llm === false && (
                <p className="error">
                  Not an AI summary: {summary.reason || "the LLM was unavailable"}
                </p>
              )}
              {summary.used_llm && summary.provider && (
                <p className="muted">Generated by {summary.provider}.</p>
              )}
            </>
          ) : (
            <p className="muted">No summary yet.</p>
          )}
          <button onClick={summarize} disabled={busy}>
            {busy ? "Working…" : summary ? "Regenerate summary" : "Summarize with LLM"}
          </button>

          <h3>Sample lines</h3>
          <ul className="samples">
            {detail.samples.map((s, i) => (
              <li key={i}>
                <code>{s.message}</code>
              </li>
            ))}
          </ul>
        </>
      )}
    </aside>
  );
}

export default function App() {
  const [clusters, setClusters] = useState([]);
  const [total, setTotal] = useState(0);
  const [sort, setSort] = useState("count");
  const [level, setLevel] = useState("");
  const [selected, setSelected] = useState(null);
  const [status, setStatus] = useState("");
  const [error, setError] = useState("");
  const [uploading, setUploading] = useState(false);
  const fileInput = useRef(null);

  const load = useCallback(async () => {
    try {
      const data = await api.clusters(sort, level);
      setClusters(data.clusters);
      setTotal(data.total_clusters);
      setError("");
    } catch (e) {
      setError(`Could not load clusters: ${e.message}`);
    }
  }, [sort, level]);

  useEffect(() => {
    load();
  }, [load]);

  async function onFile(e) {
    const file = e.target.files?.[0];
    if (!file) return;
    setUploading(true);
    setStatus("");
    try {
      const r = await api.ingest(file);
      setStatus(
        `Ingested ${r.lines_parsed.toLocaleString()} lines into ${r.clusters_touched} clusters ` +
          `in ${r.seconds}s (${r.lines_per_second.toLocaleString()} lines/s).`
      );
      await load();
    } catch (err) {
      setError(`Upload failed: ${err.message}`);
    } finally {
      setUploading(false);
      e.target.value = "";
    }
  }

  async function onReset() {
    if (!window.confirm("Delete all clusters?")) return;
    await api.reset();
    setSelected(null);
    setStatus("All data cleared.");
    load();
  }

  return (
    <div className="app">
      <header>
        <h1>Log Triage</h1>
        <p className="muted">
          Upload application logs. Similar errors are grouped into clusters and ranked, so you
          see the few problems behind thousands of lines.
        </p>
        <div className="toolbar">
          <input ref={fileInput} type="file" accept=".log,.txt,text/plain" onChange={onFile} hidden />
          <button onClick={() => fileInput.current.click()} disabled={uploading}>
            {uploading ? "Uploading…" : "Upload log file"}
          </button>
          <label>
            Sort{" "}
            <select value={sort} onChange={(e) => setSort(e.target.value)}>
              <option value="count">Most frequent</option>
              <option value="trend">Biggest recent increase</option>
              <option value="recent">Most recent</option>
            </select>
          </label>
          <label>
            Level{" "}
            <select value={level} onChange={(e) => setLevel(e.target.value)}>
              {LEVELS.map((l) => (
                <option key={l} value={l}>
                  {l || "All"}
                </option>
              ))}
            </select>
          </label>
          <button className="secondary" onClick={onReset}>
            Clear data
          </button>
        </div>
        {status && <p className="status">{status}</p>}
        {error && <p className="error">{error}</p>}
      </header>

      <main className={selected ? "with-detail" : ""}>
        <section>
          <p className="muted">{total} clusters</p>
          {clusters.length === 0 ? (
            <p className="empty">No data yet. Upload a log file to begin.</p>
          ) : (
            <table>
              <thead>
                <tr>
                  <th>Level</th>
                  <th>Pattern</th>
                  <th className="num">Count</th>
                  <th className="num">Last hr</th>
                  <th>Trend</th>
                </tr>
              </thead>
              <tbody>
                {clusters.map((c) => (
                  <tr
                    key={c.id}
                    className={selected === c.id ? "active" : ""}
                    onClick={() => setSelected(c.id)}
                  >
                    <td>
                      <LevelBadge level={c.level} />
                    </td>
                    <td className="pattern">{c.template}</td>
                    <td className="num">{c.total_count.toLocaleString()}</td>
                    <td className="num">{c.recent_count}</td>
                    <td>
                      <TrendBadge trend={c.trend} />
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          )}
        </section>
        {selected && <ClusterDetail id={selected} onClose={() => setSelected(null)} />}
      </main>
    </div>
  );
}
